#!/usr/bin/env node
// Refreshes the IANA top-level-domain snapshot used by the extractor (D32 → D44; owner approved the download
// 2026-10-16). Source: https://data.iana.org/TLD/tlds-alpha-by-domain.txt (~10 KB, plain text, one TLD per line,
// IDNs as punycode). Writes src/engine/extract/iana-tlds.ts with the file's version line, the download date and its
// SHA-256, then run `npx jest src/engine/extract/tld.test.ts` (every curated entry must still be a valid TLD).
// Usage: node scripts/update-tlds.mjs [local-copy.txt]   (curl is blocked on this Mac; Node's fetch is used)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const URL = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const local = process.argv[2];
const text = local ? readFileSync(local, 'utf8') : await (await fetch(URL)).text();
const lines = text.split(/\r?\n/);
const version = lines.find((l) => l.startsWith('#'))?.replace(/^#\s*/, '') ?? 'unknown';
const tlds = lines.filter((l) => l && !l.startsWith('#')).map((l) => l.trim().toLowerCase());
if (tlds.length < 1000 || tlds.some((t) => !/^[a-z0-9-]+$/.test(t))) throw new Error(`unexpected content (${tlds.length} entries)`);
const sha = createHash('sha256').update(text).digest('hex');
const day = new Date().toISOString().slice(0, 10);
const rows = [];
for (let i = 0; i < tlds.length; i += 16) rows.push(tlds.slice(i, i + 16).join(' '));
const out = `// GENERATED by scripts/update-tlds.mjs — do not edit. IANA root-zone TLD list (${URL}).
// ${version}; downloaded ${day}; SHA-256 ${sha}; ${tlds.length} TLDs (IDNs as punycode, lower case).
export const IANA_VERSION = ${JSON.stringify(version)};
export const IANA_SHA256 = '${sha}';
export const IANA_TLDS = \`${rows.join('\n')}\`;
`;
writeFileSync(join(import.meta.dirname, '../src/engine/extract/iana-tlds.ts'), out);
console.log(`${tlds.length} TLDs, ${version}, sha256 ${sha}`);
